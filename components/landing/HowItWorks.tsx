'use client';

import { useTranslations } from 'next-intl';
import { clsx } from 'clsx';
import { Icon } from '../Icon';
import { MatchChip } from '../MatchChip';
import { EligibilityChip } from '../EligibilityChip';
import { Reveal, useInView } from './Reveal';
import { AmbientOrbs } from './AmbientOrbs';

const STEPS = [
  { icon: 'search', key: 'step1' },
  { icon: 'verified', key: 'step2' },
  { icon: 'auto_awesome', key: 'step3' },
  { icon: 'view_kanban', key: 'step4' },
] as const;

type StepKey = (typeof STEPS)[number]['key'];

/** Live fragments of the real dashboard UI, shrunk into step cards. */
function Snippet({ index }: { index: number }) {
  if (index === 0) {
    return (
      <div className="flex flex-col gap-space-xs rounded-lg border border-outline-variant bg-surface p-space-md">
        {[
          { title: 'IT equipment for schools', score: 92 },
          { title: 'IT maintenance, Cluj-Napoca', score: 88 },
        ].map((r) => (
          <div key={r.title} className="flex items-center justify-between gap-space-xs">
            <span className="truncate font-body-sm text-body-sm text-on-surface">{r.title}</span>
            <MatchChip score={r.score} />
          </div>
        ))}
      </div>
    );
  }
  if (index === 1) {
    return (
      <div className="flex flex-col gap-space-xs rounded-lg border border-outline-variant bg-surface p-space-md">
        <div>
          <EligibilityChip eligible={true} label="Eligible" />
        </div>
        {['ISO 9001 on file', 'Cluj support point'].map((r) => (
          <div
            key={r}
            className="flex items-center gap-space-xs font-body-sm text-body-sm text-on-surface-variant"
          >
            <Icon name="check_circle" size="xs" className="text-success" />
            {r}
          </div>
        ))}
      </div>
    );
  }
  if (index === 2) {
    return (
      <div className="flex flex-col gap-space-xs rounded-lg border border-outline-variant bg-surface p-space-md">
        <div className="flex items-center justify-between gap-space-xs">
          <span className="truncate font-label-md text-label-md font-semibold text-on-surface">
            Compliance matrix
          </span>
          <span className="shrink-0 font-label-sm text-label-sm text-on-surface-variant">
            Generated by: Eligibility Checker
          </span>
        </div>
        <div className="h-1.5 rounded-full bg-surface-container-high" />
        <div className="h-1.5 w-4/5 rounded-full bg-surface-container-high" />
        <div className="h-1.5 w-3/5 rounded-full bg-surface-container-high" />
      </div>
    );
  }
  return (
    <div className="grid grid-cols-3 gap-space-xs">
      {[
        ['New', 4],
        ['Drafting', 2],
        ['Submitted', 1],
      ].map(([label, n]) => (
        <div
          key={label}
          className="flex flex-col items-center gap-1 rounded-lg bg-surface-container-low px-space-xs py-space-sm"
        >
          <span className="tnum font-headline-sm text-headline-sm text-on-surface">{n}</span>
          <span className="font-label-sm text-label-sm text-on-surface-variant">{label}</span>
        </div>
      ))}
    </div>
  );
}

function StepCard({ index, icon, stepKey }: { index: number; icon: string; stepKey: StepKey }) {
  const t = useTranslations('landing');
  const { ref, inView } = useInView<HTMLDivElement>(0.3);
  return (
    <div
      ref={ref}
      className={clsx(
        'flex h-full flex-col gap-space-sm rounded-xl border bg-surface-container-lowest p-space-lg shadow-sm transition-all duration-300 hover:-translate-y-0.5 hover:shadow-md',
        inView ? 'border-secondary/60' : 'border-outline-variant',
      )}
    >
      <div className="flex items-center gap-space-sm">
        <span
          className={clsx(
            'flex h-8 w-8 items-center justify-center rounded-full font-label-md text-label-md font-bold transition-colors duration-500',
            inView ? 'bg-navy text-white' : 'bg-surface-container-high text-on-surface-variant',
          )}
        >
          {index + 1}
        </span>
        <Icon
          name={icon}
          size="sm"
          className={inView ? 'text-secondary' : 'text-on-surface-variant'}
        />
        <h3 className="font-headline-sm text-headline-sm text-on-surface">{t(`${stepKey}Title`)}</h3>
      </div>
      <p className="font-body-md text-body-md text-on-surface-variant">{t(`${stepKey}Body`)}</p>
      <Snippet index={index} />
    </div>
  );
}

export function HowItWorks() {
  const t = useTranslations('landing');
  return (
    <section id="how" className="relative scroll-mt-20 overflow-hidden bg-surface-depth">
      <AmbientOrbs variant="light" />
      <div className="relative mx-auto flex max-w-6xl flex-col gap-space-lg px-margin py-space-xl lg:px-margin-desktop lg:py-24">
        <Reveal className="flex max-w-3xl flex-col gap-space-sm">
          <h2 className="font-headline-lg text-headline-lg tracking-tight text-on-surface">
            {t('howTitle')}
          </h2>
        </Reveal>
        <div className="grid grid-cols-1 gap-space-md md:grid-cols-2">
          {STEPS.map((s, i) => (
            <Reveal key={s.key} rise delayMs={i * 80} className="h-full">
              <StepCard index={i} icon={s.icon} stepKey={s.key} />
            </Reveal>
          ))}
        </div>
      </div>
    </section>
  );
}
